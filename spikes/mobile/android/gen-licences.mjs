// Generates licences.md (#1109): the npm lockfile and the Gradle release
// runtime classpath, with each artifact's licence read from its POM (a parent
// POM when the artifact's own names none). No dependencies; reads the Gradle
// cache that a build under toolchain.sh filled.
// usage: node gen-licences.mjs > licences.md
import { readFileSync, readdirSync, existsSync } from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';

const here = new URL('.', import.meta.url).pathname;
const cache = join(
  process.env.GRADLE_USER_HOME ?? join(homedir(), '.cache/conch/gradle-home'),
  'caches/modules-2/files-2.1',
);

function pomFor(g, a, v) {
  const dir = join(cache, g, a, v);
  if (!existsSync(dir)) return null;
  for (const h of readdirSync(dir)) {
    const f = join(dir, h, `${a}-${v}.pom`);
    if (existsSync(f)) return readFileSync(f, 'utf8');
  }
  return null;
}

function licenceOf(g, a, v, depth = 0) {
  const pom = pomFor(g, a, v);
  if (pom === null) return 'POM not in cache';
  const block = /<licenses>([\s\S]*?)<\/licenses>/.exec(pom.replace(/<parent>[\s\S]*?<\/parent>/, (m) => m));
  if (block) {
    const names = [...block[1].matchAll(/<name>([\s\S]*?)<\/name>/g)].map((m) => m[1].trim());
    if (names.length) return names.join('; ');
  }
  const p = /<parent>([\s\S]*?)<\/parent>/.exec(pom);
  if (p && depth < 5) {
    const t = (n) => new RegExp(`<${n}>([^<]*)</${n}>`).exec(p[1])?.[1].trim();
    return licenceOf(t('groupId'), t('artifactId'), t('version'), depth + 1);
  }
  return 'none declared in POM';
}

function gradleRows(file, config) {
  const rows = new Set();
  for (const line of readFileSync(file, 'utf8').split('\n')) {
    if (line.startsWith('#') || line.startsWith('empty=')) continue;
    const [coord, configs] = line.split('=');
    if (configs?.split(',').includes(config)) rows.add(coord);
  }
  return [...rows].sort().map((c) => {
    const [g, a, v] = c.split(':');
    return `| \`${c}\` | ${licenceOf(g, a, v)} |`;
  });
}

const lock = JSON.parse(readFileSync(join(here, 'package-lock.json'), 'utf8'));
const pkg = JSON.parse(readFileSync(join(here, 'package.json'), 'utf8'));
const out = [];
out.push('# Licences of the Android spike', '');
out.push('Generated by `node gen-licences.mjs > licences.md` after a build under `toolchain.sh`. Do not edit by hand.', '');
out.push('## npm: direct dependencies', '', '| Package | Version | Licence |', '| --- | --- | --- |');
const direct = { ...pkg.dependencies, ...pkg.devDependencies };
for (const n of Object.keys(direct).sort()) {
  const e = lock.packages[`node_modules/${n}`];
  out.push(`| \`${n}\` | ${e.version} | ${e.license} |`);
}
const counts = {};
for (const [k, e] of Object.entries(lock.packages)) {
  if (k === '') continue;
  counts[e.license] = (counts[e.license] ?? 0) + 1;
}
out.push('', '## npm: the whole lockfile', '', `${Object.values(counts).reduce((a, b) => a + b, 0)} packages (transitive included), by licence:`, '');
out.push('| Licence | Packages |', '| --- | --- |');
for (const [l, n] of Object.entries(counts).sort((a, b) => b[1] - a[1])) out.push(`| ${l} | ${n} |`);

out.push('', '## Gradle: release runtime classpath (`android/app/gradle.lockfile`)', '');
out.push('Shipped in the APK. Licence read from the POM.', '', '| Artifact | Licence |', '| --- | --- |');
out.push(...gradleRows(join(here, 'android/app/gradle.lockfile'), 'releaseRuntimeClasspath'));
out.push('', '## Gradle: build plugins (`android/buildscript-gradle.lockfile`)', '');
out.push('Build time only; not in the APK.', '', '| Artifact | Licence |', '| --- | --- |');
out.push(...gradleRows(join(here, 'android/buildscript-gradle.lockfile'), 'classpath'));
console.log(out.join('\n'));
